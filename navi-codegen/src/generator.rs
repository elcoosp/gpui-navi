use crate::config::NaviConfig;
use crate::scanner::scan_routes;
use anyhow::Result;
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn sanitize_ident(s: &str) -> String {
    let replaced = s.replace(['(', ')', '-', '.', '$', '{', '}'], "_");
    let mut result = String::new();
    let mut last_was_underscore = false;
    for ch in replaced.chars() {
        if ch == '_' {
            if !last_was_underscore {
                result.push('_');
                last_was_underscore = true;
            }
        } else {
            result.push(ch);
            last_was_underscore = false;
        }
    }
    result.trim_end_matches('_').to_lowercase()
}

fn is_snake_case(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        // Identifiers must not start with a digit.
        Some(first) if first.is_ascii_lowercase() || first == '_' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
}

/// Generate the route-tree module source for the given configuration.
///
/// # Errors
/// Propagates scanner errors (invalid route files).
pub fn generate_route_tree(config: &NaviConfig) -> Result<String> {
    let routes = scan_routes(config)?;

    let mut route_nodes = String::new();
    let mut module_decls = BTreeSet::new();
    let mut register_calls = String::new();

    for route in &routes {
        let parent_field = match &route.parent {
            Some(parent) => format!("Some(\"{parent}\".into())"),
            None => "None".to_string(),
        };

        let module_path = &route.module_name;
        let route_type = &route.route_type_name;
        let file_path = route.relative_path.to_str().unwrap_or_default();

        let raw_ident = sanitize_ident(&module_path.replace("::", "_"));
        // `sanitize_ident` lowercases, so the only way to leave snake_case is
        // a leading digit (e.g. a `404.rs` route file), which is not a valid
        // Rust identifier — prefix an underscore for those.
        let mod_ident = if is_snake_case(&raw_ident) {
            raw_ident
        } else {
            format!("_{raw_ident}")
        };
        let mod_decl = format!("#[path = \"routes/{file_path}\"] pub mod {mod_ident};");
        module_decls.insert(mod_decl);

        let node_block = format!(
            "\n    {{\n        let mut node = {mod_ident}::{route_type}::build_node();\n        node.parent = {parent_field};\n        tree.add_route(node);\n    }}\n"
        );

        if let Some(feature) = &route.cfg_feature {
            let _ = write!(route_nodes, "\n#[cfg(feature = \"{feature}\")]{node_block}");
        } else {
            route_nodes.push_str(&node_block);
        }

        let register_line = match &route.cfg_feature {
            Some(feature) => {
                format!("#[cfg(feature = \"{feature}\")] {mod_ident}::{route_type}::register();\n")
            }
            None => format!("{mod_ident}::{route_type}::register();\n"),
        };
        register_calls.push_str(&register_line);
    }

    let module_decls_str = module_decls
        .iter()
        .map(String::as_str)
        .collect::<Vec<_>>()
        .join("\n");

    Ok(format!(
        "// AUTO-GENERATED by navi-codegen - DO NOT EDIT\n\n\
// Module declarations for discovered routes\n\
{module_decls_str}\n\n\
/// Build the route tree with all discovered routes.\n\
pub fn build_route_tree() -> navi_router::RouteTree {{\n\
    let mut tree = navi_router::RouteTree::new();\n\
{route_nodes}\n    tree\n}}\n\n\
/// Register all route components and loaders.\n\
pub fn register_routes() {{\n\
{register_calls}}}\n"
    ))
}

/// Generate and write the route tree, skipping the write when the content is
/// unchanged so downstream build scripts do not trigger needless rebuilds.
///
/// # Errors
/// Propagates scanner errors and filesystem errors from writing the output.
pub fn write_route_tree(config: &NaviConfig) -> Result<()> {
    let content = generate_route_tree(config)?;
    let out_path = Path::new(&config.generated_route_tree);
    if let Some(parent) = out_path.parent() {
        fs::create_dir_all(parent)?;
    }
    if fs::read_to_string(out_path).is_ok_and(|existing| existing == content) {
        return Ok(());
    }
    fs::write(out_path, content)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::path::PathBuf;

    fn temp_root(tag: &str) -> PathBuf {
        static COUNTER: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
        let n = COUNTER.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
        let root = std::env::temp_dir().join(format!("navi-gen-{}-{tag}-{n}", std::process::id()));
        fs::create_dir_all(root.join("src/routes")).expect("mkdir");
        root
    }

    fn config_for(root: &Path) -> NaviConfig {
        NaviConfig {
            routes_directory: root.join("src/routes").to_string_lossy().into_owned(),
            generated_route_tree: root
                .join("src/route_tree.gen.rs")
                .to_string_lossy()
                .into_owned(),
            ..NaviConfig::default()
        }
    }

    const DEFINE: &str = "define_route!(T, path: \"/t\");";

    #[test]
    fn test_generate_contains_modules_and_calls() {
        let root = temp_root("basic");
        fs::write(root.join("src/routes/first.rs"), DEFINE).expect("write");
        let config = config_for(&root);
        let out = generate_route_tree(&config).expect("ok");
        assert!(out.contains("// AUTO-GENERATED by navi-codegen - DO NOT EDIT"));
        assert!(out.contains("pub mod first;"));
        assert!(out.contains("first::T::build_node()"));
        assert!(out.contains("first::T::register();"));
        assert!(out.contains("pub fn build_route_tree() -> navi_router::RouteTree"));
        assert!(out.contains("pub fn register_routes()"));
    }

    #[test]
    fn test_generate_parent_assignment() {
        let root = temp_root("parent");
        fs::write(
            root.join("src/routes/users.rs"),
            "define_route!(UsersLayout, path: \"/users\");",
        )
        .expect("write");
        fs::create_dir_all(root.join("src/routes/users")).expect("mkdir");
        fs::write(
            root.join("src/routes/users/index.rs"),
            "define_route!(UsersIndex, path: \"/users\", is_index: true);",
        )
        .expect("write");
        let config = config_for(&root);
        let out = generate_route_tree(&config).expect("ok");
        assert!(
            out.contains("node.parent = Some(\"UsersLayout\".into())"),
            "{out}"
        );
    }

    #[test]
    fn test_generate_cfg_feature_gating() {
        let root = temp_root("cfg");
        fs::write(
            root.join("src/routes/secret.rs"),
            "#[cfg(feature = \"x\")]\ndefine_route!(S, path: \"/s\");",
        )
        .expect("write");
        let config = config_for(&root);
        let out = generate_route_tree(&config).expect("ok");
        assert!(out.contains("#[cfg(feature = \"x\")]"));
        assert!(out.contains("#[cfg(feature = \"x\")] secret::S::register();"));
    }

    #[test]
    fn test_generate_numeric_module_gets_prefixed() {
        let root = temp_root("numeric");
        fs::write(root.join("src/routes/404.rs"), DEFINE).expect("write");
        let config = config_for(&root);
        let out = generate_route_tree(&config).expect("ok");
        assert!(
            out.contains("pub mod _404;"),
            "numeric module must be prefixed: {out}"
        );
    }

    fn modified_time(path: &str) -> std::time::SystemTime {
        std::fs::metadata(path)
            .and_then(|m| m.modified())
            .unwrap_or(std::time::UNIX_EPOCH)
    }

    #[test]
    fn test_write_is_idempotent() {
        let root = temp_root("idem");
        fs::write(root.join("src/routes/one.rs"), DEFINE).expect("write");
        let config = config_for(&root);
        write_route_tree(&config).expect("first write");
        let first = modified_time(&config.generated_route_tree);
        std::thread::sleep(std::time::Duration::from_millis(120));
        write_route_tree(&config).expect("second write");
        let second = modified_time(&config.generated_route_tree);
        assert_eq!(first, second, "unchanged content must not rewrite the file");
        // Changing routes (new route id) must rewrite.
        std::thread::sleep(std::time::Duration::from_millis(120));
        fs::write(
            root.join("src/routes/two.rs"),
            "define_route!(Two, path: \"/two\");",
        )
        .expect("write");
        write_route_tree(&config).expect("third write");
        let third = modified_time(&config.generated_route_tree);
        assert_ne!(first, third, "changed content must rewrite the file");
    }

    #[test]
    fn test_write_creates_parent_dirs() {
        let root = temp_root("dirs");
        let mut config = config_for(&root);
        config.generated_route_tree = root
            .join("deep/nested/tree.gen.rs")
            .to_string_lossy()
            .into_owned();
        write_route_tree(&config).expect("ok");
        assert!(root.join("deep/nested/tree.gen.rs").is_file());
    }

    #[test]
    fn test_sanitize_ident_collapses_underscores() {
        assert_eq!(sanitize_ident("a--b__c"), "a_b_c");
        assert_eq!(sanitize_ident("($id)"), "_id");
        assert_eq!(sanitize_ident("X.Y-Z$W"), "x_y_z_w");
        assert_eq!(sanitize_ident("trailing__"), "trailing");
    }

    #[test]
    fn test_is_snake_case() {
        assert!(is_snake_case("abc_123"));
        assert!(is_snake_case("_private"));
        assert!(!is_snake_case("abcD"));
        assert!(!is_snake_case(""));
        assert!(!is_snake_case("404"));
        assert!(is_snake_case("_404"), "underscore prefix is valid");
    }
}
